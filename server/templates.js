/** Initial repository files generated for each project. */

export function projectMd(name, kickoff, ownerName) {
  return `# ${name}

> Project record generated by Project OS for Codex. Git history is the source of truth for progress.

## Who this is for
${kickoff.forWhom || '(Not provided)'}

## Intended outcome
${kickoff.goal || '(Not provided)'}

## Acceptance criteria
${(kickoff.acceptance || []).map((item) => `- [ ] ${item}`).join('\n') || '- (Not provided)'}

## Out of scope for this iteration
${kickoff.notDoing || '(Not defined)'}

## Owner
${ownerName || '(Not assigned)'}
`;
}

